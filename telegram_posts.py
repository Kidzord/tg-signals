def _load_used() -> set[int]:
    if USED_PATH.exists():
        try:
            return set(json.loads(USED_PATH.read_text(encoding="utf-8")))
        except Exception:
            return set()
    return set()


def _save_used(used: set[int]) -> None:
    USED_PATH.write_text(json.dumps(sorted(used)), encoding="utf-8")


def next_unused() -> int | None:
    used = _load_used()
    for i in range(1, len(POSTS) + 1):
        if i not in used:
            return i
    return None


def mark_used(n: int) -> None:
    used = _load_used()
    used.add(n)
    _save_used(used)


def remaining() -> int:
    return len(POSTS) - len(_load_used())
