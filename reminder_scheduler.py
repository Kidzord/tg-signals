def get_next_post_num():
    """Получить номер следующего поста."""
    USED_PATH = Path(__file__).parent / "threads_used.json"
    used = set()
    if USED_PATH.exists():
        try:
            used = set(json.loads(USED_PATH.read_text(encoding="utf-8")))
        except:
            pass

    for i in range(1, 29):
        if i not in used:
            return i
    return 1

