def _clip(text: str) -> tuple[bool, str]:
    """Копируем текст в буфер обмена Windows. Возвращаем (успех, способ/причина).

    Текст уходит в PowerShell через -EncodedCommand (UTF-16LE), поэтому кавычки,
    переводы строк и кириллица не ломаются. Если PowerShell недоступен — clip.exe.
    """
    ps = ("$t=[Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('"
          + base64.b64encode(text.encode("utf-8")).decode("ascii")
          + "')); Set-Clipboard -Value $t")
    enc = base64.b64encode(ps.encode("utf-16-le")).decode("ascii")
    reason = ""
    try:
        r = subprocess.run(["powershell", "-NoProfile", "-NonInteractive",
                            "-EncodedCommand", enc],
                           capture_output=True, timeout=25)
        if r.returncode == 0:
            return True, "PowerShell"
        err = (r.stderr or b"").decode("utf-8", "replace").strip()[:200]
        reason = err or f"код {r.returncode}"
    except Exception as e:
        reason = str(e)[:200]

    # Запасной путь: clip.exe понимает UTF-16LE из перенаправленного файла.
    try:
        import tempfile

        fd, tmp = tempfile.mkstemp(suffix=".txt")
        os.close(fd)
        try:
            with open(tmp, "wb") as f:
                f.write(text.encode("utf-16-le"))
            with open(tmp, "rb") as f:
                r = subprocess.run(["clip"], stdin=f, capture_output=True, timeout=25)
            if r.returncode == 0:
                return True, "clip.exe"
            reason += f"; clip.exe: код {r.returncode}"
        finally:
            try:
                os.remove(tmp)
            except OSError:
                pass
    except Exception as e:
        reason += f"; clip.exe: {e}"

    return False, reason.replace("\n", " ").strip() or "неизвестная причина"


def _load_used() -> set:
    if USED_PATH.exists():
        try:
            return set(json.loads(USED_PATH.read_text(encoding="utf-8")))
        except Exception:
            return set()
    return set()


def _save_used(used: set) -> None:
    USED_PATH.write_text(json.dumps(sorted(used)), encoding="utf-8")


def next_unused() -> int | None:
    """Номер первого неопубликованного поста. None — банк исчерпан."""
    used = _load_used()
    for i in range(1, len(POSTS) + 1):
        if i not in used:
            return i
    return None


def mark_used(n: int) -> None:
    """Отметить пост опубликованным (общий список с ручным композером)."""
    used = _load_used()
    used.add(n)
    _save_used(used)


def show() -> None:
    used = _load_used()
    for i, p in enumerate(POSTS, 1):
        mark = "✓" if i in used else " "
        print(f"[{mark}] {i:>2}. {p['title']}")


