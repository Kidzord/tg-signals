def _load() -> dict:
    if os.path.exists(STATE_PATH):
        try:
            with open(STATE_PATH, encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, dict):
                return data
        except (OSError, ValueError):
            pass
    return {}


def _save(st: dict) -> None:
    tmp = STATE_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(st, f, ensure_ascii=False, indent=2)
    os.replace(tmp, STATE_PATH)


def start_date() -> dt.date:
    """День запуска дневника: DEVLOG_START из окружения или зафиксированный."""
    env = os.getenv("DEVLOG_START", "").strip()
    if env:
        try:
            return dt.date.fromisoformat(env)
        except ValueError:
            pass
    st = _load()
    raw = str(st.get("start", "") or "")
    if raw:
        try:
            return dt.date.fromisoformat(raw)
        except ValueError:
            pass
    today = dt.date.today()
    st["start"] = today.isoformat()
    _save(st)
    return today


def day_number(now: dt.date | None = None) -> int:
    """Номер дня дневника: с даты старта, включительно («сегодня — день 1»)."""
    now = now or dt.date.today()
    return max(1, (now - start_date()).days + 1)


def next_devnote() -> str | None:
    """Очередная неиспользованная заметка из разработки (или None, если исчерпан)."""
    st = _load()
    used = {int(i) for i in st.get("used", []) if str(i).lstrip("-").isdigit()}
    for i in range(len(DEVNOTES)):
        if i not in used:
            st["used"] = sorted(used | {i})
            _save(st)
            return DEVNOTES[i]
    return None


def next_devnotes(k: int = 2) -> list[str]:
    """До k очередных заметок — для еженедельной сводки."""
    out: list[str] = []
    for _ in range(max(0, int(k))):
        note = next_devnote()
        if note is None:
            break
        out.append(note)
    return out
